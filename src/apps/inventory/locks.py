"""قفل ردیفی واحد — لایهٔ اول تضمین عدم‌هم‌پوشانی (ADR-0020).

هر عملی که بازه‌ای از یک واحد را اشغال می‌کند (رزرو، جابه‌جایی، بلوک) پیش از
بررسی تداخل، ردیف همان واحد را قفل می‌کند. نتیجه: عملیات هم‌زمانِ **یک** واحد
پشت سر هم اجرا می‌شوند و بررسی تداخل همیشه تازه‌ترین دادهٔ ثبت‌شده را می‌بیند
(``READ COMMITTED``)؛ عملیات واحدهای مختلف هیچ انتظاری برای هم ندارند.

تریگر پایگاه‌داده همین قفل را دوباره می‌گیرد (در همان تراکنش، بی‌هزینه)، پس
حتی مسیری که این تابع را فراموش کند هم نمی‌تواند رزرو هم‌پوشان بسازد.
"""

from __future__ import annotations

from apps.inventory.models import Unit


def lock_unit(unit: Unit) -> None:
    """قفل انحصاری ردیف واحد تا پایان تراکنش جاری (بیرون از تراکنش ⇒ خطا)."""
    Unit._base_manager.select_for_update().filter(pk=unit.pk).values_list("pk", flat=True).first()
